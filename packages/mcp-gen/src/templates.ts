/** Code that puts a credential on the request; `credential` is an expression (the env var by default). */
function applyBody(binding: AuthBinding, credential = `process.env.${binding.envVar}!`): string {
  switch (binding.kind) {
    case "apiKey-header":
      return `  headers[${JSON.stringify(binding.paramName)}] = ${credential};`;
    case "apiKey-query":
      return `  url.searchParams.set(${JSON.stringify(binding.paramName)}, ${credential});`;
    case "bearer":
      return `  headers["authorization"] = \`Bearer \${${credential}}\`;`;
    case "basic": {
      return `  headers["authorization"] = \`Basic \${Buffer.from(${credential}).toString("base64")}\`;`;
    }
    case "passthrough":
      return `  if (!callerToken) {
    throw new Error("This tool requires the caller's own bearer token, but none was provided with the request.");
  }
  headers["authorization"] = \`Bearer \${callerToken}\`;`;
    case "none":
    default:
      return "  // no-op";
  }
}

/**
 * Who may call the MCP endpoint. Separate from auth.ts, which is how this
 * server authenticates to the *upstream* API. Configured entirely through
 * standard environment variables, so it runs the same anywhere:
 *
 *   MCP_ACCESS_KEY_SHA256       comma-separated SHA-256 hashes (hex) of accepted access keys
 *   MCP_OAUTH_ISSUER            OAuth 2.1 issuer whose access tokens are accepted
 *   MCP_OAUTH_JWKS_URL          optional; defaults to <issuer>/.well-known/jwks.json
 *   MCP_OAUTH_ALLOWED_SUBJECTS  comma-separated token subjects (user ids) allowed in
 *   MCP_OAUTH_AUDIENCE          accept tokens issued for this audience (any subject) instead
 *   MCP_OAUTH_UPSTREAM_KEY      key (base64url, 32 bytes) to decrypt the caller's own upstream
 *                               credential from their token, for per-user credentials
 *   MCP_PUBLIC_URL              optional; this server's public origin, for OAuth metadata
 *   MCP_ALLOW_UNAUTHENTICATED   "true" to accept every caller (local testing only)
 */
export function accessTemplate(binding: AuthBinding): string {
  const passthrough = binding.kind === "passthrough";
  return `// Generated by altship-mcp. Do not hand-edit — regenerate from the source spec instead.
//
// Access control for the MCP endpoint: every request must carry an access
// key or an OAuth access token from an allowed user. Keys are compared by
// SHA-256 hash, so this server never holds them in plain text.
import { createDecipheriv, createHash, timingSafeEqual } from "node:crypto";
import { createRemoteJWKSet, jwtVerify } from "jose";

/** The header an access key can always be sent in.${passthrough ? " Required in this server's per-user auth mode, where Authorization carries the caller's own token for the upstream API." : ""} */
export const ACCESS_KEY_HEADER = "x-mcp-access-key";
const PASSTHROUGH = ${passthrough};

const list = (value: string | undefined) =>
  (value ?? "")
    .split(",")
    .map((v) => v.trim())
    .filter(Boolean);

const keyHashes = list(process.env.MCP_ACCESS_KEY_SHA256).map((h) => Buffer.from(h.toLowerCase(), "hex"));
const issuer = process.env.MCP_OAUTH_ISSUER?.replace(/\\/$/, "");
const allowedSubjects = new Set(list(process.env.MCP_OAUTH_ALLOWED_SUBJECTS));
const audience = process.env.MCP_OAUTH_AUDIENCE || undefined;
const upstreamKey = process.env.MCP_OAUTH_UPSTREAM_KEY ? Buffer.from(process.env.MCP_OAUTH_UPSTREAM_KEY, "base64url") : undefined;
const jwks = issuer
  ? createRemoteJWKSet(new URL(process.env.MCP_OAUTH_JWKS_URL ?? \`\${issuer}/.well-known/jwks.json\`))
  : undefined;

/** Whether OAuth sign-in is configured (and the protected-resource metadata should be served). */
export const OAUTH_ENABLED = Boolean(issuer && !PASSTHROUGH);

export type Headers = Record<string, string | string[] | undefined>;
/** On success, \`credential\` is the caller's own upstream credential when their token carries one. */
export type AccessResult =
  | { ok: true; credential?: string }
  | { ok: false; status: number; message: string; wwwAuthenticate?: string };

function header(headers: Headers, name: string): string | undefined {
  const value = headers[name];
  return Array.isArray(value) ? value[0] : value;
}

function bearer(headers: Headers): string | undefined {
  return header(headers, "authorization")?.match(/^Bearer\\s+(.+)$/i)?.[1];
}

function isAccessKey(candidate: string): boolean {
  const hash = createHash("sha256").update(candidate).digest();
  return keyHashes.some((expected) => expected.length === hash.length && timingSafeEqual(expected, hash));
}

/** Decrypts an AES-256-GCM value encoded as base64url(iv[12] | ciphertext | tag[16]). */
function decryptCredential(sealed: string): string | undefined {
  if (!upstreamKey) return undefined;
  try {
    const raw = Buffer.from(sealed, "base64url");
    const decipher = createDecipheriv("aes-256-gcm", upstreamKey, raw.subarray(0, 12));
    decipher.setAuthTag(raw.subarray(raw.length - 16));
    return Buffer.concat([decipher.update(raw.subarray(12, raw.length - 16)), decipher.final()]).toString("utf8");
  } catch {
    return undefined;
  }
}

/**
 * Verifies an OAuth access token. Accepted when it's signed by the issuer and
 * either names an allowed subject or was issued for this server's audience.
 * Returns null if not accepted, or the caller's own credential if it carries one.
 */
async function verifyToken(token: string): Promise<{ credential?: string } | null> {
  if (!jwks || !issuer) return null;
  try {
    const { payload } = await jwtVerify(token, jwks, { issuer, ...(audience ? { audience } : {}) });
    const subjectAllowed = typeof payload.sub === "string" && allowedSubjects.has(payload.sub);
    if (!subjectAllowed && !(audience && allowedSubjects.size === 0)) return null;
    if (typeof payload.upc !== "string") return {};
    const credential = decryptCredential(payload.upc);
    return credential === undefined ? null : { credential };
  } catch {
    return null;
  }
}

/** This server's public origin: MCP_PUBLIC_URL, or the request's own host. */
export function publicOrigin(headers: Headers): string {
  if (process.env.MCP_PUBLIC_URL) return process.env.MCP_PUBLIC_URL.replace(/\\/$/, "");
  const proto = header(headers, "x-forwarded-proto") ?? "https";
  return \`\${proto}://\${header(headers, "x-forwarded-host") ?? header(headers, "host") ?? "localhost"}\`;
}

/** RFC 9728 protected-resource metadata: tells MCP clients where to sign in. */
export function protectedResourceMetadata(headers: Headers, mcpPath: string) {
  return {
    resource: \`\${publicOrigin(headers)}\${mcpPath}\`,
    authorization_servers: [issuer],
    bearer_methods_supported: ["header"],
  };
}

export async function checkAccess(headers: Headers): Promise<AccessResult> {
  if (process.env.MCP_ALLOW_UNAUTHENTICATED === "true") return { ok: true };
  if (keyHashes.length === 0 && !OAUTH_ENABLED) {
    return {
      ok: false,
      status: 500,
      message: "No access configured: set MCP_ACCESS_KEY_SHA256 or MCP_OAUTH_ISSUER (or MCP_ALLOW_UNAUTHENTICATED=true for local testing).",
    };
  }

  const headerKey = header(headers, ACCESS_KEY_HEADER);
  if (headerKey && isAccessKey(headerKey)) return { ok: true };

  if (!PASSTHROUGH) {
    const token = bearer(headers);
    if (token && isAccessKey(token)) return { ok: true };
    const verified = token ? await verifyToken(token) : null;
    if (verified) return { ok: true, credential: verified.credential };
  }

  return {
    ok: false,
    status: 401,
    message: PASSTHROUGH
      ? \`Missing or invalid access key. Send it in the \${ACCESS_KEY_HEADER} header.\`
      : "Missing or invalid access key or token. Send it as Authorization: Bearer <key>.",
    wwwAuthenticate: OAUTH_ENABLED
      ? \`Bearer resource_metadata="\${publicOrigin(headers)}/.well-known/oauth-protected-resource"\`
      : undefined,
  };
}
`;
}

