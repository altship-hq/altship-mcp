function needsEnvVar(binding: AuthBinding, perUserCredential = false): boolean {
  return !perUserCredential && binding.kind !== "none" && binding.kind !== "passthrough";
}

function authDescription(binding: AuthBinding, perUserCredential = false): string {
  if (perUserCredential && needsEnvVar(binding)) {
    return "None to configure here — each person who connects signs in with their own credential for the upstream API, delivered encrypted inside their access token (see Access).";
  }
  if (binding.kind === "passthrough") {
    return "None to configure here — each caller forwards their own bearer token, which is relayed to the upstream API as-is.";
  }
  if (binding.kind === "none") {
    return "No credentials required (no supported auth scheme was found in the source spec).";
  }
  return `\`${binding.envVar}\` — required credential for the upstream API.`;
}

